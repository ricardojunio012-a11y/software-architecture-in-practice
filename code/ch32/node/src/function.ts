// The "function" version: one month of financial reports as a function. Generates a
// few real PDFs with the function's code and simulates the whole month of calls.
import { createHash } from "node:crypto";
import { mkdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { generatePdf } from "./function/report.ts";
import { cost, FUNCTION, type Execution } from "./platform.ts";
import { BATCH_CONCURRENCY, MIN, monthOfReports, sampleReport } from "./reports.ts";
import { num, usd } from "./prices.ts";

const data = process.argv[2] ?? "/data";
const { units, eBatch, eOnDemand } = monthOfReports();
const all = [...eBatch, ...eOnDemand];
const c = cost(all);

const pct = (n: number, of: number) => `${num((100 * n) / of, 1)}%`;
const percentile = (xs: number[], p: number) =>
  [...xs].sort((a, b) => a - b)[Math.ceil((p / 100) * xs.length) - 1];
const latency = (e: Execution[]) => e.map((x) => x.end - x.start);
const colds = (e: Execution[]) => e.filter((x) => x.cold).length;
const batchEnd = Math.max(...eBatch.map((e) => e.end));
const batchTime = Math.round((batchEnd - 2 * 60 * MIN) / 1000);
const batchBilled = eBatch.reduce((s, e) => s + e.billed, 0) / 1000;

const row = (label: string, e: Execution[]) =>
  label.padEnd(19) +
  num(e.length, 0).padStart(8) +
  `${colds(e)} (${pct(colds(e), e.length)})`.padStart(17) +
  String(percentile(latency(e), 50)).padStart(11) +
  String(percentile(latency(e), 99)).padStart(11);

const out = [
  `function: ${FUNCTION.memoryMb} MB; cold start of ${FUNCTION.init} ms; ` +
    `idle environment goes away after ${FUNCTION.idleTimeout / MIN} min`,
  "",
  "PDFs generated by the function's code (the first 3 communities):",
];
for (let i = 0; i < 3; i++) {
  const pdf = generatePdf(sampleReport(i, units[i]));
  const hash = createHash("sha256").update(pdf).digest("hex").slice(0, 16);
  const id = `community-000${i + 1}`;
  out.push(`  ${id}  ${units[i]} units  ${pdf.length} bytes  sha256 ${hash}...`);
  mkdirSync(join(data, "output", "pdf"), { recursive: true });
  writeFileSync(join(data, "output", "pdf", `${id}.pdf`), pdf);
}
out.push(
  "",
  "".padEnd(19) +
    "calls".padStart(8) +
    "cold starts".padStart(17) +
    "p50 (ms)".padStart(11) +
    "p99 (ms)".padStart(11),
  row("batch on the 1st", eBatch),
  row("on demand, month", eOnDemand),
  "",
  `the batch took ${batchTime} s, with up to ${BATCH_CONCURRENCY} executions ` +
    `in parallel; billed time: ${num(batchBilled, 0)} s`,
  `billed for the month: ${num(all.length, 0)} requests and ` +
    `${num(c.gbSeconds, 0)} GB-s = ${usd(c.dollars)}`,
);

const folder = join(data, "output", "function");
mkdirSync(folder, { recursive: true });
writeFileSync(join(folder, "result.txt"), out.join("\n") + "\n");
console.log(out.join("\n"));
